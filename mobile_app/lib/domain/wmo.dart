/// Метки европейского AQI: уровень 0 — зелёный, 1 — янтарный, 2 — красный.
({int level, String text}) aqiInfo(num aqi) {
  final n = aqi.round();
  final level = aqi < 40
      ? 0
      : aqi < 60
      ? 1
      : 2;
  final label = n < 20
      ? "Отличное"
      : n < 40
      ? "Хорошее"
      : n < 60
      ? "Среднее"
      : n < 80
      ? "Плохое"
      : n < 100
      ? "Очень плохое"
      : "Крайне плохое";
  return (level: level, text: "$n · $label");
}

/// "6 · высокий" для УФ-индекса.
String uvText(num uv) {
  final n = uv.round();
  final d = n < 3
      ? "низкий"
      : n < 6
      ? "умер."
      : n < 8
      ? "высокий"
      : n < 11
      ? "оч. высок."
      : "экстрим";
  return "$n · $d";
}

/// "2026-09-18T06:38" → "06:38".
String isoToHM(String iso) {
  if (iso.isEmpty) return "--:--";
  final parts = iso.split("T");
  if (parts.length < 2) return "--:--";
  final t = parts[1];
  return t.length >= 5 ? t.substring(0, 5) : "--:--";
}

/// Подпись дня прогноза: "Сегодня", далее Вс/Пн/… (алгоритм Сакамото).
String dayLabel(String isoDate, int index) {
  if (index == 0) return "Сегодня";
  const names = ["Вс", "Пн", "Вт", "Ср", "Чт", "Пт", "Сб"];
  final y = int.tryParse(isoDate.substring(0, 4)) ?? 1970;
  final m = int.tryParse(isoDate.substring(5, 7)) ?? 1;
  final d = int.tryParse(isoDate.substring(8, 10)) ?? 1;
  final t = [0, 3, 2, 5, 0, 3, 5, 1, 4, 6, 2, 4][m - 1];
  var yy = y;
  if (m < 3) yy--;
  return names[(yy + yy ~/ 4 - yy ~/ 100 + yy ~/ 400 + t + d) % 7];
}
