List<String> tempJokes(double feelsLike, String unitLabel) {
  var c = feelsLike;
  if (unitLabel == "°F") c = (feelsLike - 32) * 5 / 9;
  for (final (threshold, variants) in _tempBuckets) {
    if (c < threshold) return variants;
  }
  return _tempBuckets.last.$2;
}

