bool isSnowy(int c) => const [71, 73, 75, 77, 85, 86].contains(c);

bool isFoggy(int c) => c == 45 || c == 48;

String _pick(List<String> arr, Random random) =>
    arr.isEmpty ? "" : arr[random.nextInt(arr.length)];

/// Реплика для текущей погоды. [windMs] и [uv] — уже нормализованы
/// (ветер в м/с). [unitLabel] — "°C"/"°F" подпись отображаемой единицы.
String feelsLikeJoke({
  required double feelsLike,
  required String unitLabel,
  required int wmo,
  required double windMs,
  required double uv,
  Random? random,
}) {
  final rnd = random ?? Random();
  final specials = <String>[];
  if (wmo >= 95) specials.addAll(_stormJokes);
  if (isRainy(wmo)) specials.addAll(_rainJokes);
  if (isSnowy(wmo)) specials.addAll(_snowJokes);
  if (isFoggy(wmo)) specials.addAll(_fogJokes);
  if (windMs >= 10) specials.addAll(_windJokes);
  if (uv >= 7) specials.addAll(_uvJokes);
  if (specials.isNotEmpty && rnd.nextDouble() < 0.7) {
    return _pick(specials, rnd);
  }
  return _pick(tempJokes(feelsLike, unitLabel), rnd);
}
